// Scans src/components/<id>/version-<N>/variants/<slug>/ and writes the documentation registry to
// src/generated/ (git-ignored, never edited by hand):
//   doc-registry.ts                  → eager: versions of each component, the slugs of their examples and
//                                      their base/<id>.html + example.html imported as text
//   examples/<id>.version-<N>.ts     → lazy, one per version: example components + their HTML/TS as text
// Contents are never copied here: files are imported with `with { loader: 'text' }`, so `ng serve`
// itself reloads any edit (title, description, example). Only creating or deleting folders needs a
// regeneration (ng serve / npm start via scripts/ng-builders, npm run docs, npm run new:variant do it).
// That is what lets a maquetador add an example by creating a folder, with no import or registration.
//
//   node scripts/generate-docs.mjs                  → generate once
//   node scripts/generate-docs.mjs --watch -- <cmd> → generate, regenerate on any change, run <cmd>
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, watch, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SRC_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'src');
const COMPONENTS_DIR = join(SRC_DIR, 'components');
const OUTPUT_DIR = join(SRC_DIR, 'generated');
const EXAMPLES_DIR = join(OUTPUT_DIR, 'examples');

const VERSION_FOLDER = /^version-(\d+)$/;
const KEBAB_CASE = /^[a-z0-9]+(-[a-z0-9]+)*$/;
/** `static readonly status: … = 'done';` in the class of base/<id>.ts; missing means pending. */
const STATUS_PROPERTY = /static\s+readonly\s+status\b[^=;]*=\s*['"]([\w-]+)['"]/;
const STATUSES = ['pending', 'in-progress', 'done'];
const DEFAULT_STATUS = 'pending';
/** `static readonly designer = 'Yony León';` in the class of base/<id>.ts. */
const DESIGNER_PROPERTY = /static\s+readonly\s+designer\b[^=;]*=\s*(['"])(.*?)\1/;
const HEADER = [
  '// AUTO-GENERATED by scripts/generate-docs.mjs from the version-<N>/variants/<slug>/ folders.',
  '// Do not edit: it is rewritten by `npm start`, `npm run build`, `npm test` and `npm run docs`.',
];

const subfolders = (dir) =>
  existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => entry.name)
        .sort()
    : [];

/** "_demo_" → "demo": underscores mark a reference folder (sorted first on disk), not part of the ID. */
const componentId = (dir) => dir.replace(/^_+|_+$/g, '');

/** Import of a file as text (contents are read by the bundler, so edits are picked up by ng serve). */
const textImport = (name, path) => `import ${name} from '${path}' with { loader: 'text' };`;

/** Example folders of one version: variants/<slug>/ with an example.ts. */
function findExamples(dir, folder) {
  const variantsDir = join(COMPONENTS_DIR, dir, folder, 'variants');
  return subfolders(variantsDir).filter((slug) => {
    const where = `src/components/${dir}/${folder}/variants/${slug}`;
    if (!KEBAB_CASE.test(slug)) {
      console.warn(`[docs] ${where}: folder name must be kebab-case. Skipped.`);
      return false;
    }
    if (!existsSync(join(variantsDir, slug, 'example.ts'))) {
      console.warn(`[docs] ${where}: missing example.ts. Skipped.`);
      return false;
    }
    return true;
  });
}

/** Status of one version, from the `static readonly status` property of the class in its base/<id>.ts. */
function readStatus(dir, folder, id) {
  const file = join(COMPONENTS_DIR, dir, folder, 'base', `${id}.ts`);
  if (!existsSync(file)) return DEFAULT_STATUS;
  const status = STATUS_PROPERTY.exec(readFileSync(file, 'utf8'))?.[1];
  if (!status) return DEFAULT_STATUS;
  if (STATUSES.includes(status)) return status;
  console.warn(`[docs] src/components/${dir}/${folder}/base/${id}.ts: status must be ${STATUSES.join(' | ')}.`);
  return DEFAULT_STATUS;
}

/** Designer of one version, from `static readonly designer = '<name>';` in its base/<id>.ts ('' = none). */
function readDesigner(dir, folder, id) {
  const file = join(COMPONENTS_DIR, dir, folder, 'base', `${id}.ts`);
  if (!existsSync(file)) return '';
  return DESIGNER_PROPERTY.exec(readFileSync(file, 'utf8'))?.[2].trim() ?? '';
}

/** Lazy chunk of one version: every example module + its example.html and example.ts as text. */
function renderExamples(dir, folder, examples) {
  const imports = examples.flatMap((slug, i) => {
    const path = `../../components/${dir}/${folder}/variants/${slug}/example`;
    const hasHtml = existsSync(join(COMPONENTS_DIR, dir, folder, 'variants', slug, 'example.html'));
    return [
      `import * as example${i} from '${path}';`,
      ...(hasHtml ? [textImport(`html${i}`, `${path}.html`)] : []),
      '// @ts-ignore: the example.ts source itself, as text for the code panel.',
      textImport(`ts${i}`, `${path}.ts`),
    ];
  });
  const entries = examples.map((slug, i) => {
    const hasHtml = existsSync(join(COMPONENTS_DIR, dir, folder, 'variants', slug, 'example.html'));
    return [
      '  {',
      `    slug: '${slug}',`,
      `    module: example${i},`,
      `    sources: { html: ${hasHtml ? `html${i}` : "''"}, ts: ts${i} as string },`,
      '  },',
    ].join('\n');
  });
  return [
    ...HEADER,
    "import { DocExampleSource } from '../../service/catalog.model';",
    ...imports,
    '',
    'export default [',
    ...entries,
    '] satisfies readonly DocExampleSource[];',
    '',
  ].join('\n');
}

/** All output files, keyed by path relative to src/generated/. */
function render() {
  const files = new Map();
  const imports = [];
  const registry = subfolders(COMPONENTS_DIR).flatMap((dir) => {
    const id = componentId(dir);
    const versions = subfolders(join(COMPONENTS_DIR, dir))
      .map((folder) => ({ folder, number: Number(VERSION_FOLDER.exec(folder)?.[1]) }))
      .filter((version) => version.number > 0)
      .sort((a, b) => a.number - b.number)
      .map(({ folder, number }) => {
        const examples = findExamples(dir, folder);
        const chunk = `${id}.${folder}`;
        if (examples.length) files.set(`examples/${chunk}.ts`, renderExamples(dir, folder, examples));

        // Title/description headers: base/<id>.html (component) and each example.html (variant).
        const base = `../components/${dir}/${folder}/base/${id}.html`;
        const hasBase = existsSync(join(OUTPUT_DIR, base));
        if (hasBase) imports.push(textImport(`html${imports.length}`, base));
        const baseName = hasBase ? `html${imports.length - 1}` : undefined;
        const exampleHtml = examples.flatMap((slug) => {
          const path = `../components/${dir}/${folder}/variants/${slug}/example.html`;
          if (!existsSync(join(OUTPUT_DIR, path))) return [];
          imports.push(textImport(`html${imports.length}`, path));
          return [`        '${slug}': html${imports.length - 1},`];
        });
        return [
          '    {',
          `      number: ${number},`,
          `      folder: '${folder}',`,
          `      status: '${readStatus(dir, folder, id)}',`,
          `      designer: ${JSON.stringify(readDesigner(dir, folder, id))},`,
          ...(baseName ? [`      html: ${baseName},`] : []),
          `      examples: [${examples.map((slug) => `'${slug}'`).join(', ')}],`,
          ...(exampleHtml.length ? ['      exampleHtml: {', ...exampleHtml, '      },'] : []),
          ...(examples.length ? [`      loadExamples: () => import('./examples/${chunk}'),`] : []),
          '    },',
        ].join('\n');
      });
    return versions.length ? [`  '${id}': [\n${versions.join('\n')}\n  ],`] : [];
  });

  files.set(
    'doc-registry.ts',
    [
      ...HEADER,
      "import { DocRegistry } from '../service/catalog.model';",
      ...imports,
      '',
      'export const DOC_REGISTRY: DocRegistry = {',
      ...registry,
      '};',
      '',
    ].join('\n'),
  );
  return files;
}

function generate() {
  const files = render();
  mkdirSync(EXAMPLES_DIR, { recursive: true });

  // Chunks of examples or versions that no longer exist.
  for (const name of readdirSync(EXAMPLES_DIR)) {
    if (!files.has(`examples/${name}`)) rmSync(join(EXAMPLES_DIR, name));
  }

  const changed = [...files].filter(([path, content]) => {
    const file = join(OUTPUT_DIR, path);
    if (existsSync(file) && readFileSync(file, 'utf8') === content) return false;
    writeFileSync(file, content);
    return true;
  });
  if (changed.length) console.log(`[docs] src/generated updated (${changed.length} file(s))`);
}

if (!process.argv.includes('--watch')) {
  generate();
} else {
  // Watch mode must never die while `ng serve` keeps running, or the page silently stops updating:
  // a file being saved (EBUSY on Windows) or a folder deleted mid-scan only skips this round.
  const safeGenerate = () => {
    try {
      generate();
    } catch (error) {
      console.warn(`[docs] ${error.message} (retrying)`);
      clearTimeout(timer);
      timer = setTimeout(safeGenerate, 300);
    }
  };
  let timer;
  const schedule = () => {
    clearTimeout(timer);
    timer = setTimeout(safeGenerate, 100);
  };

  // fs.watch is fast but can miss events or fail on Windows (atomic saves, deleted folders):
  // restart it on error, and re-scan every second as a safety net (only changed files are written).
  const startWatcher = () => {
    try {
      watch(COMPONENTS_DIR, { recursive: true }, schedule).on('error', (error) => {
        console.warn(`[docs] watcher: ${error.message} (restarting)`);
        setTimeout(startWatcher, 500);
      });
    } catch (error) {
      console.warn(`[docs] watcher: ${error.message} (restarting)`);
      setTimeout(startWatcher, 500);
    }
  };
  safeGenerate();
  startWatcher();
  setInterval(safeGenerate, 1000);
  process.on('uncaughtException', (error) => console.warn(`[docs] ${error.message}`));

  const separator = process.argv.indexOf('--');
  if (separator > 0) {
    const [command, ...args] = process.argv.slice(separator + 1);
    const child = spawn(command, args, { stdio: 'inherit', shell: true });
    child.on('exit', (code) => process.exit(code ?? 0));
    // Ctrl+C or closing the terminal stops both processes.
    for (const signal of ['SIGINT', 'SIGTERM']) {
      process.on(signal, () => {
        child.kill(signal);
        process.exit(0);
      });
    }
  }
}
